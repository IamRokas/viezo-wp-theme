/**
 * Generates src/scss/sprites.scss from src/images/icons/*.svg.
 *
 * Each icon becomes a data URI usable via the `sprite()` mixin
 * (src/scss/global/_sprites-mixin.scss). Attributes written as
 * `var:color.fill="#1661AB"` become overridable variables: the value is
 * replaced with `___color___` and `#1661AB` is stored as the default.
 */
import fs from 'node:fs';
import path from 'node:path';
import { optimize } from 'svgo';

const root = path.resolve(import.meta.dirname, '..');
const iconsDir = path.resolve(root, 'src/images/icons');
const outFile = path.resolve(root, 'src/scss/sprites.scss');

const toDataUri = (svg) =>
	'data:image/svg+xml,' +
	svg
		.replace(/"/g, "'")
		.replace(/%/g, '%25')
		.replace(/</g, '%3c')
		.replace(/>/g, '%3e')
		.replace(/#/g, '%23');

const scssMap = (name, entries) =>
	`$${name}: (\n${entries.join(',\n')}\n);\n`;

function parseIcon(file) {
	let svg = fs.readFileSync(file, 'utf8');
	const variables = {};

	svg = svg.replace(/var:([\w-]+)\.([\w-]+)="([^"]*)"/g, (match, variable, attr, value) => {
		variables[variable] = value;
		return `${attr}="___${variable}___"`;
	});

	const tag = svg.match(/<svg[^>]*>/)?.[0] ?? '';
	const attr = (key) => tag.match(new RegExp(`\\s${key}="([\\d.]+)`))?.[1];
	const viewBox = tag.match(/viewBox="([^"]+)"/)?.[1]?.split(/[\s,]+/);
	const width = attr('width') ?? viewBox?.[2];
	const height = attr('height') ?? viewBox?.[3];

	const { data } = optimize(svg, {
		multipass: true,
		plugins: [
			{ name: 'preset-default', params: { overrides: { convertColors: false } } },
			'removeDimensions',
		],
	});

	return { uri: toDataUri(data), width, height, variables };
}

export function generateSprites() {
	const icons = fs
		.readdirSync(iconsDir)
		.filter((f) => f.endsWith('.svg') && f !== 'sprite.svg')
		.sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }))
		.map((f) => ({ name: path.basename(f, '.svg'), ...parseIcon(path.join(iconsDir, f)) }));

	const sprites = icons.map((i) => `    '${i.name}': "${i.uri}"`);
	const sizes = icons
		.filter((i) => i.width && i.height)
		.map((i) => `    '${i.name}': (\n        'width': ${i.width}px,\n        'height': ${i.height}px\n    )`);
	const variables = icons
		.filter((i) => Object.keys(i.variables).length)
		.map(
			(i) =>
				`    '${i.name}': (\n${Object.entries(i.variables)
					.map(([k, v]) => `        '${k}': '${v}'`)
					.join(',\n')}\n    )`
		);

	const output = [
		'// Generated by scripts/vite-svg-sprites.js from src/images/icons. Do not edit.\n',
		scssMap('sprites', sprites),
		scssMap('sizes', sizes),
		scssMap('variables', variables),
	].join('\n');

	// Only write when changed, so the dev server doesn't loop on its own output.
	if (!fs.existsSync(outFile) || fs.readFileSync(outFile, 'utf8') !== output) {
		fs.writeFileSync(outFile, output);
	}
}

export default function svgSprites() {
	return {
		name: 'viezo:svg-sprites',
		buildStart() {
			generateSprites();
		},
		configureServer(server) {
			server.watcher.add(iconsDir);
			const onChange = (file) => {
				if (file.startsWith(iconsDir) && file.endsWith('.svg')) {
					generateSprites();
				}
			};
			server.watcher.on('add', onChange);
			server.watcher.on('change', onChange);
			server.watcher.on('unlink', onChange);
		},
	};
}
